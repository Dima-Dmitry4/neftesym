// Свойства флюидов (in-situ + surface).
// Полевые метрические единицы. Все константы — числа, никаких
// "единиц" в типах (TypeScript не умеет в phantom types без
// усложнений, но в комментариях и тестах это явно проверяется).

export interface FluidProperties {
  /** Вязкость нефти в пласте, сП. */
  muOilCP: number;
  /** Вязкость воды в пласте, сП. */
  muWaterCP: number;
  /** Плотность нефти в пласте, кг/м³. */
  rhoOilKgM3: number;
  /** Плотность воды в пласте, кг/м³. */
  rhoWaterKgM3: number;
  /** Плотность нефти на поверхности (для пересчёта м³ → т), кг/м³. */
  rhoOilSurface: number;
  /** Сжимаемость нефти, атм⁻¹. */
  coAtm: number;
  /** Сжимаемость воды, атм⁻¹. */
  cwAtm: number;
  /** Объёмный коэффициент нефти, м³(пл)/м³(поверхн). */
  bo: number;
  /** Объёмный коэффициент воды, м³(пл)/м³(поверхн). */
  bw: number;
}
