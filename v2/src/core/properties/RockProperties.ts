// Свойства породы (однородные по умолчанию, неоднородные — картой).

export interface RockProperties {
  /** Пористость, доли (0..1). */
  porosity: number;
  /** Средняя горизонтальная проницаемость, мД.
   *  Используется в дефолтном генераторе; реальные карты — в Reservoir. */
  permHMeanMD: number;
  /** Анизотропия k_v / k_h, безразмерная. */
  permAnisotropy: number;
  /** Сжимаемость породы, атм⁻¹. */
  crAtm: number;
}
